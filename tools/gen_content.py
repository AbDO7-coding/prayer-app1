def norm(s):
    s = re.sub("[\u064B-\u065F\u0670\u0640\u06D6-\u06ED]", "", s)
    s = re.sub("[أإآٱ]", "ا", s).replace("ى", "ي").replace("ة", "ه").replace("ؤ", "و").replace("ئ", "ي")
    return re.sub(r"\s+", " ", s).strip()

errors = []
seen = {}
for i, r in enumerate(H):
    r["id"] = "h%03d" % (i + 1)
    n = norm(r["text"])
    if n in seen: errors.append("duplicate text %s == %s" % (r["id"], seen[n]))
    seen[n] = r["id"]
    for f in ("text", "narrator", "coll", "num", "gc", "gt", "grader"):
        if not r[f]: errors.append("%s missing %s" % (r["id"], f))
    if r["gc"] not in ("sahih", "hasan"): errors.append("%s bad grade class" % r["id"])
    for c in r["cats"]:
        if c not in CODES: errors.append("%s unknown category %s" % (r["id"], c))
